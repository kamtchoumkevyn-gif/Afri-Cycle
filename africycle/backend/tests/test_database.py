# ---- SQL translation for Postgres ----

def test_placeholders_become_psycopg_style():
    assert to_postgres("SELECT * FROM users WHERE id = ?") == "SELECT * FROM users WHERE id = %s"


def test_camel_case_names_are_quoted_so_postgres_keeps_their_case():
    sql = "SELECT n.*, s.name AS sellerName FROM notifications n WHERE n.sellerId = ?"
    assert to_postgres(sql) == (
        'SELECT n.*, s.name AS "sellerName" FROM notifications n WHERE n."sellerId" = %s'
    )


def test_lowercase_names_and_keywords_are_left_alone():
    sql = "SELECT status, COUNT(*) AS count FROM notifications GROUP BY status"
    assert to_postgres(sql) == sql


def test_text_in_quotes_is_untouched():
    sql = "SELECT * FROM users WHERE role = 'what? isFlagged 100%' AND name = ?"
    assert to_postgres(sql) == "SELECT * FROM users WHERE role = 'what? isFlagged 100%' AND name = %s"


def test_percent_signs_are_escaped_when_parameters_are_passed():
    assert to_postgres("SELECT 5 % 2, ?") == "SELECT 5 %% 2, %s"
    assert to_postgres("SELECT 5 % 2", has_params=False) == "SELECT 5 % 2"


def test_schema_uses_postgres_types():
    for statement in SCHEMA:
        translated = to_postgres(statement, has_params=False)
        assert "AUTOINCREMENT" not in translated
        assert " REAL" not in translated
        assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in translated
    users = to_postgres(SCHEMA[0], has_params=False)
    assert '"phoneNumber" TEXT UNIQUE NOT NULL' in users
    assert '"isFlagged" INTEGER DEFAULT 0' in users
    prices = to_postgres(SCHEMA[3], has_params=False)
    assert '"pricePerKg" DOUBLE PRECISION NOT NULL' in prices
    assert 'FOREIGN KEY ("materialCategoryId") REFERENCES material_category(id)' in prices


def test_tables_are_listed_in_creation_order():
    assert TABLES == ["users", "material_category", "buyer_profile", "buyer_prices",
                      "transactions", "notifications", "chat_messages", "material_photos"]


# ---- lastrowid emulation ----

class FakePsycopgCursor:
    def __init__(self, returned_row):
        self.returned_row = returned_row
        self.executed = None

    def execute(self, sql, params):
        self.executed = (sql, params)

    def fetchone(self):
        return self.returned_row


def test_insert_asks_postgres_for_the_new_id():
    fake = FakePsycopgCursor({"id": 42})
    cursor = PostgresCursor(fake)
    cursor.execute("\n  INSERT INTO users (phoneNumber, name) VALUES (?, ?)\n  ", ("677000001", "Paul"))
    assert fake.executed == (
        '\n  INSERT INTO users ("phoneNumber", name) VALUES (%s, %s) RETURNING id', ("677000001", "Paul")
    )
    assert cursor.lastrowid == 42


def test_skipped_insert_leaves_lastrowid_empty():
    cursor = PostgresCursor(FakePsycopgCursor(None))
    cursor.execute("INSERT INTO material_category (name) VALUES (?) ON CONFLICT (name) DO NOTHING", ("Plastic",))
    assert cursor.lastrowid is None


def test_other_statements_are_not_changed_beyond_translation():
    fake = FakePsycopgCursor(None)
    PostgresCursor(fake).execute("UPDATE users SET isFlagged = 1 WHERE id = ?", (3,))
    assert fake.executed == ('UPDATE users SET "isFlagged" = 1 WHERE id = %s', (3,))
